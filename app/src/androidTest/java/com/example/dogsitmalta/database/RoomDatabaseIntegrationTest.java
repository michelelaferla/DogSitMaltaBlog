package com.example.dogsitmalta.database;

import android.content.Context;

import androidx.room.Room;
import androidx.test.core.app.ApplicationProvider;
import androidx.test.ext.junit.runners.AndroidJUnit4;

import com.example.dogsitmalta.database.entities.PostEntity;
import com.example.dogsitmalta.database.entities.UserEntity;
import com.example.dogsitmalta.database.interfaces.PostDao;
import com.example.dogsitmalta.database.interfaces.UserDao;

import org.junit.After;
import org.junit.Before;
import org.junit.Test;
import org.junit.runner.RunWith;

import java.util.List;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

/**
 * Instrumented integration tests for {@link BlogRoomDatabase}, {@link PostDao}, and {@link UserDao}.
 * Uses an in-memory database to execute isolated database operations on a real SQLite engine.
 */
@RunWith(AndroidJUnit4.class)
public class RoomDatabaseIntegrationTest {

    private BlogRoomDatabase db;
    private PostDao postDao;
    private UserDao userDao;

    @Before
    public void createDb() {
        Context context = ApplicationProvider.getApplicationContext();
        db = Room.inMemoryDatabaseBuilder(context, BlogRoomDatabase.class)
                .allowMainThreadQueries()
                .build();
        postDao = db.postDao();
        userDao = db.userDao();
    }

    @After
    public void closeDb() {
        if (db != null) {
            db.close();
        }
    }

    // ==========================================
    // 1. INSERTING RECORDS
    // ==========================================

    @Test
    public void insertPost_returnsAutoGeneratedId() {
        PostEntity post = createSamplePost("Dog Walking in Sliema", "Looking for sitter", "Sliema");
        long id = postDao.insert(post);

        assertTrue("Generated ID should be positive", id > 0);
    }

    @Test
    public void insertUser_returnsAutoGeneratedId() {
        UserEntity user = createSampleUser("John", "Doe", "john.doe@example.com");
        long id = userDao.insert(user);

        assertTrue("Generated User ID should be positive", id > 0);
    }

    // ==========================================
    // 2. RETRIEVING RECORDS
    // ==========================================

    @Test
    public void retrievePostByIdAndRemoteId_returnsInsertedPost() {
        PostEntity post = createSamplePost("Pet Sitting Valletta", "Need weekend sitter", "Valletta");
        post.remoteId = "remote-uuid-101";
        long id = postDao.insert(post);
        post.id = id;

        PostEntity retrievedById = postDao.findVisible(id);
        assertNotNull(retrievedById);
        assertEquals("Pet Sitting Valletta", retrievedById.title);
        assertEquals("Valletta", retrievedById.location);

        PostEntity retrievedByRemoteId = postDao.findByRemoteId("remote-uuid-101");
        assertNotNull(retrievedByRemoteId);
        assertEquals(id, retrievedByRemoteId.id);
    }

    @Test
    public void retrieveUserByEmailAndUid_supportsCaseInsensitiveEmailLookup() {
        UserEntity user = createSampleUser("Jane", "Smith", "Jane.Smith@Example.com");
        user.firebaseUid = "fb-uid-999";
        userDao.insert(user);

        // Test case-insensitive email lookup (NOCASE index)
        UserEntity foundByLower = userDao.findByEmail("jane.smith@example.com");
        assertNotNull(foundByLower);
        assertEquals("Jane", foundByLower.name);
        assertEquals("Smith", foundByLower.surname);

        UserEntity foundByUid = userDao.findByUid("fb-uid-999");
        assertNotNull(foundByUid);
        assertEquals("Jane.Smith@Example.com", foundByUid.email);
    }

    // ==========================================
    // 3. UPDATING RECORDS
    // ==========================================

    @Test
    public void updatePost_modifiesExistingRecord() {
        PostEntity post = createSamplePost("Old Title", "Old Message", "Old Location");
        long id = postDao.insert(post);

        PostEntity loaded = postDao.findVisible(id);
        loaded.title = "New Updated Title";
        loaded.message = "New Updated Message";
        loaded.location = "New Location";
        loaded.latitude = 35.899;
        loaded.longitude = 14.514;
        int updatedRows = postDao.update(loaded);

        assertEquals(1, updatedRows);

        PostEntity reloaded = postDao.findVisible(id);
        assertEquals("New Updated Title", reloaded.title);
        assertEquals("New Updated Message", reloaded.message);
        assertEquals("New Location", reloaded.location);
        assertEquals(Double.valueOf(35.899), reloaded.latitude);
        assertEquals(Double.valueOf(14.514), reloaded.longitude);
    }

    @Test
    public void updateUser_attachesFirebaseUidAndUpdatesPassword() {
        UserEntity user = createSampleUser("Mark", "Zerafa", "mark@example.com");
        userDao.insert(user);

        int uidResult = userDao.attachFirebaseUid("mark@example.com", "firebase-uid-777");
        assertEquals(1, uidResult);

        UserEntity updatedUidUser = userDao.findByEmail("mark@example.com");
        assertNotNull(updatedUidUser);
        assertEquals("firebase-uid-777", updatedUidUser.firebaseUid);

        long now = System.currentTimeMillis();
        int passResult = userDao.updatePassword("MARK@EXAMPLE.COM", "pbkdf2_new_hash", now);
        assertEquals(1, passResult);

        UserEntity updatedPassUser = userDao.findByEmail("mark@example.com");
        assertEquals("pbkdf2_new_hash", updatedPassUser.passwordHash);
        assertEquals(Long.valueOf(now), updatedPassUser.passwordUpdatedAt);
    }

    // ==========================================
    // 4. SEARCHING FOR RECORDS
    // ==========================================

    @Test
    public void searchPosts_matchesTitleMessageLocationAndIgnoresDeleted() {
        PostEntity post1 = createSamplePost("Golden Retriever", "Needs daily walk", "Mdina");
        PostEntity post2 = createSamplePost("Cat Sitting", "Looking for cat lover", "Sliema");
        PostEntity post3 = createSamplePost("Poodle Care", "Retriever friendly", "Valletta");
        long id1 = postDao.insert(post1);
        long id2 = postDao.insert(post2);
        long id3 = postDao.insert(post3);

        // Search term matching title in post1 and message in post3
        List<PostEntity> results = postDao.search("Retriever");
        assertEquals(2, results.size());

        // Soft delete post1
        postDao.softDelete(id1, System.currentTimeMillis());

        // Search term should now return only post3
        List<PostEntity> postDeleteResults = postDao.search("Retriever");
        assertEquals(1, postDeleteResults.size());
        assertEquals(id3, postDeleteResults.get(0).id);
    }

    // ==========================================
    // 5. HANDLING NONEXISTENT RECORDS
    // ==========================================

    @Test
    public void queryNonexistentRecords_returnsNull() {
        assertNull(postDao.findVisible(9999L));
        assertNull(postDao.findAny(9999L));
        assertNull(postDao.findByRemoteId("nonexistent-uuid-000"));
        assertNull(userDao.findByEmail("nonexistent@domain.com"));
        assertNull(userDao.findByUid("nonexistent-uid-000"));
    }

    // ==========================================
    // 6. DELETING OR SOFT-DELETING RECORDS
    // ==========================================

    @Test
    public void softDeletePost_marksDeletedAndDirtyWithoutRemovingFromDatabase() {
        PostEntity post = createSamplePost("To Be Soft Deleted", "Message content", "St. Julian's");
        long id = postDao.insert(post);

        long deleteTimestamp = System.currentTimeMillis();
        int rowsAffected = postDao.softDelete(id, deleteTimestamp);
        assertEquals(1, rowsAffected);

        // Should no longer be visible via findVisible() or allVisible()
        assertNull(postDao.findVisible(id));
        assertEquals(0, postDao.allVisible().size());

        // Must still exist in database via findAny() with deleted=true and dirty=true
        PostEntity anyPost = postDao.findAny(id);
        assertNotNull(anyPost);
        assertTrue(anyPost.deleted);
        assertTrue(anyPost.dirty);
        assertEquals(deleteTimestamp, anyPost.updatedAt);
    }

    // ==========================================
    // 7. VERIFYING DATABASE CONSTRAINTS
    // ==========================================

    @Test
    public void insertUserWithDuplicateEmail_failsDueToUniqueIndex() {
        UserEntity user1 = createSampleUser("User1", "One", "duplicate@example.com");
        long id1 = userDao.insert(user1);
        assertTrue(id1 > 0);

        // Insert duplicate email (even with different case)
        UserEntity user2 = createSampleUser("User2", "Two", "DUPLICATE@EXAMPLE.COM");
        long id2 = userDao.insert(user2);

        // OnConflictStrategy.IGNORE returns -1 upon constraint violation
        assertEquals(-1L, id2);
    }

    @Test
    public void insertUserWithDuplicateFirebaseUid_failsDueToUniqueIndex() {
        UserEntity user1 = createSampleUser("Alice", "A", "alice@example.com");
        user1.firebaseUid = "shared-uid-123";
        userDao.insert(user1);

        UserEntity user2 = createSampleUser("Bob", "B", "bob@example.com");
        user2.firebaseUid = "shared-uid-123";
        long id2 = userDao.insert(user2);

        assertEquals(-1L, id2);
    }

    @Test
    public void insertPostWithDuplicateRemoteId_failsDueToUniqueIndex() {
        PostEntity post1 = createSamplePost("Post 1", "Content 1", "Location 1");
        post1.remoteId = "unique-remote-uuid";
        postDao.insert(post1);

        PostEntity post2 = createSamplePost("Post 2", "Content 2", "Location 2");
        post2.remoteId = "unique-remote-uuid";
        long id2 = postDao.insert(post2);

        assertEquals(-1L, id2);
    }

    // ==========================================
    // 8. VERIFYING PARAMETERIZED QUERIES PREVENT SQL INJECTION
    // ==========================================

    @Test
    public void searchAndEmailQueries_treatSqlInjectionPayloadsAsLiteralData() {
        PostEntity normalPost = createSamplePost("Normal Title", "Normal Message", "Malta");
        postDao.insert(normalPost);

        // SQL injection payload attempting tautology
        String injectionPayload = "' OR '1'='1";

        List<PostEntity> searchResults = postDao.search(injectionPayload);
        // Room binds :term as a string parameter; payload must not match normal text or drop tables
        assertTrue("Search should treat payload literally and return no results", searchResults.isEmpty());

        // SQL injection payload attempting DDL execution
        String dropPayload = "'; DROP TABLE posts; --";
        List<PostEntity> dropResults = postDao.search(dropPayload);
        assertTrue("DDL payload must be treated as literal data", dropResults.isEmpty());

        // Verify the database table still exists and functions properly
        assertEquals(1, postDao.allVisible().size());

        // Test SQL injection attempt in UserDao email lookup
        UserEntity injectedUser = userDao.findByEmail("' OR '1'='1");
        assertNull("Email query should treat payload as literal text", injectedUser);
    }

    // ==========================================
    // HELPER METHODS
    // ==========================================

    private PostEntity createSamplePost(String title, String message, String location) {
        PostEntity p = new PostEntity();
        p.title = title;
        p.message = message;
        p.location = location;
        p.createdAt = System.currentTimeMillis();
        p.updatedAt = System.currentTimeMillis();
        p.remoteId = java.util.UUID.randomUUID().toString();
        p.dirty = true;
        p.deleted = false;
        return p;
    }

    private UserEntity createSampleUser(String name, String surname, String email) {
        UserEntity u = new UserEntity();
        u.name = name;
        u.surname = surname;
        u.email = email;
        u.passwordHash = "210000:salt:hash";
        u.createdAt = System.currentTimeMillis();
        u.active = true;
        u.profileUpdatedAt = System.currentTimeMillis();
        return u;
    }
}
